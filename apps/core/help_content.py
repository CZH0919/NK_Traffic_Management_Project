def available_topics(user):
    admin = user.is_authenticated and user.has_perm('core.manage_system')
    return [dict(t, legacy_anchors=[key for key, slug in ALIASES.items()
                 if slug == t['slug'] and key != slug])
            for t in TOPICS if not t['admin'] or admin]


def search_topics(topics, query):
    words = query.casefold().replace('比较流量', '比较 流量').replace('流量比较', '流量 比较').split()
    if not words:
        return []
    found = []
    for t in topics:
        sections = [('steps', '操作步骤', ' '.join(t['steps'])),
                    ('fields', '填写说明', ' '.join(' '.join(x) for x in t['fields'])),
                    ('results', '怎样读结果', ' '.join(t['results'])),
                    ('questions', '常见问题', ' '.join(' '.join(x) for x in t['questions']))]
        candidates = []
        for anchor, label, content in sections:
            text = ' '.join((t['title'], t['summary'], t['keywords'], content)).casefold()
            if all(word in text for word in words):
                index = next((content.casefold().find(w) for w in words if w in content.casefold()), 0)
                candidates.append((sum(word in content.casefold() for word in words),
                    dict(topic=t, anchor=anchor, label=label, excerpt=content[max(0,index-30):max(0,index-30)+160])))
        if candidates:
            found.append(max(candidates, key=lambda pair:pair[0])[1])
    return found
